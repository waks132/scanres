class ADWINDetector:
    """Détecteur de concept drift ADWIN (ADaptive WINdowing)"""
    
    def __init__(self, delta=0.002):
        self.delta = delta
        self.window = []
        
    def detect_drift(self, data_stream):
        """Détecte un changement dans le flux de données"""
        if len(data_stream) < 10:
            return False
        
        mid = len(data_stream) // 2
        mean1 = np.mean(data_stream[:mid])
        mean2 = np.mean(data_stream[mid:])
        std = np.std(data_stream)
        
        if std == 0:
            return False
        
        z_score = abs(mean1 - mean2) / (std / np.sqrt(len(data_stream)))
        return z_score > 2.5


class DynamicIDS:
    """
    IDS dynamique avec:
    - Online learning
    - Détection de concept drift (ADWIN)
    - Randomisation adaptative des seuils
    - Rotation d'ensemble de détecteurs
    - A2: Replay buffer pour adversarial retraining
    """
    
    def __init__(self, threshold=2.5, adaptation_rate=0.1, replay_buffer_size=5000):
        self.threshold = threshold
        self.base_threshold = threshold
        self.adaptation_rate = adaptation_rate
        self.detection_history = []
        self.drift_detector = ADWINDetector()
        self.false_positive_rate = 0.05
        self.active_detector = 0
        self.detectors = [
            {'name': 'PCA', 'threshold': threshold},
            {'name': 'Kernel', 'threshold': threshold * 1.2},
            {'name': 'Ensemble', 'threshold': threshold * 0.8},
        ]
        
        # A2: Replay buffer pour adversarial retraining
        self.replay_buffer = deque(maxlen=replay_buffer_size)
        self.episode_count = 0
        
    def detect(self, score):
        """Détecte une intrusion avec seuil adaptatif et rotation"""
        # Rotation des détecteurs
        detector = self.detectors[self.active_detector]
        
        # Randomisation du seuil
        noise = np.random.normal(0, detector['threshold'] * 0.05)
        effective_threshold = detector['threshold'] + noise
        
        detected = score > effective_threshold
        self.detection_history.append((score, detected))
        
        # Détection de concept drift
        if len(self.detection_history) > 20:
            recent_scores = [s for s, d in self.detection_history[-20:]]
            if self.drift_detector.detect_drift(recent_scores):
                self._adapt_threshold()
                self.active_detector = (self.active_detector + 1) % len(self.detectors)
        
        # Limiter l'historique
        if len(self.detection_history) > 1000:
            self.detection_history = self.detection_history[-500:]
        
        return detected
    
    def add_to_replay(self, perturbation, detected, episode):
        """A2: Ajoute une perturbation au replay buffer pour retraining"""
        self.replay_buffer.append({
            'perturbation': perturbation,
            'detected': detected,
            'episode': episode,
            'timestamp': time.time()
        })
        self.episode_count = episode
    
    def should_retrain(self, retrain_interval=20, min_samples=500):
        """A2: Détermine si l'IDS doit être retrainé sur les évasions récentes"""
        return (self.episode_count > 0 and 
                self.episode_count % retrain_interval == 0 and 
                len(self.replay_buffer) >= min_samples)
    
    def get_adversarial_batch(self, batch_size=100):
        """A2: Retourne un batch de perturbations récentes pour retraining"""
        if len(self.replay_buffer) < batch_size:
            return []
        # Sélectionner les perturbations qui ont échappé à la détection (évasions réussies)
        evasions = [item for item in self.replay_buffer if not item['detected']]
        if len(evasions) < batch_size // 2:
            # Pas assez d'évasions, prendre toutes les perturbations récentes
            recent = list(self.replay_buffer)[-batch_size:]
            return [item['perturbation'] for item in recent]
        return [item['perturbation'] for item in evasions[-batch_size:]]
    
    def retrain(self, perturbations):
        """A2: Met à jour les seuils basés sur les perturbations adversariales récentes"""
        if len(perturbations) == 0:
            return
        
        # Calculer les scores de détection pour les perturbations adversariales
        scores = [np.linalg.norm(p) for p in perturbations]
        if len(scores) > 0:
            new_threshold = np.percentile(scores, 95) * 1.2
            for det in self.detectors:
                det['threshold'] = new_threshold * (1 + np.random.uniform(-0.1, 0.1))
            print(f"[IDS ADVERSARIAL] Retraining effectué. Nouveau seuil: {new_threshold:.3f}")
    
    def _adapt_threshold(self):
        """Adapte le seuil en cas de drift détecté"""
        recent_scores = [s for s, d in self.detection_history[-50:]]
        new_threshold = np.percentile(recent_scores, 95) * 1.2
        
        for det in self.detectors:
            det['threshold'] = new_threshold * (1 + np.random.uniform(-0.1, 0.1))
        
        print(f"[IDS DYNAMIQUE] Seuil adapté: {new_threshold:.3f} (détecteur: {self.detectors[self.active_detector]['name']})")


