class NonlinearDetector:
    """
    Détecteur d'anomalies avancé avec:
    - Kernel PCA pour patterns non-linéaires
    - Ensemble: Isolation Forest + LOF + reconstruction error
    - Vote majoritaire adaptatif
    """
    
    def __init__(self, engine: OptimizedSVDEngine):
        self.engine = engine
        self.kpca = None
        self.iso_forest = None
        self.lof = None
        self.kpca_threshold = None
        
    def fit(self, node_embeddings):
        """Entraîne les détecteurs sur les embeddings"""
        # Kernel PCA avec noyau RBF
        self.kpca = KernelPCA(
            n_components=10, 
            kernel='rbf', 
            gamma=0.1, 
            fit_inverse_transform=True,
            random_state=42
        )
        self.kpca.fit(node_embeddings)
        
        # Calcul du seuil de reconstruction
        kpca_projection = self.kpca.transform(node_embeddings)
        reconstruction = self.kpca.inverse_transform(kpca_projection)
        kpca_errors = np.linalg.norm(node_embeddings - reconstruction, axis=1)
        self.kpca_threshold = np.percentile(kpca_errors, 90)
        
        # Isolation Forest amélioré
        self.iso_forest = IsolationForest(
            contamination=0.1, 
            random_state=42, 
            n_estimators=200,
            max_samples='auto'
        )
        self.iso_forest.fit(node_embeddings)
        
        # Local Outlier Factor (mode novelty)
        self.lof = LocalOutlierFactor(
            n_neighbors=10, 
            contamination=0.1, 
            novelty=True
        )
        self.lof.fit(node_embeddings)
        
    def predict(self, node_embeddings):
        """Prédit les anomalies avec vote majoritaire"""
        # Kernel PCA reconstruction error
        kpca_projection = self.kpca.transform(node_embeddings)
        reconstruction = self.kpca.inverse_transform(kpca_projection)
        kpca_errors = np.linalg.norm(node_embeddings - reconstruction, axis=1)
        kpca_anomaly = kpca_errors > self.kpca_threshold
        
        # Isolation Forest
        if_anomaly = self.iso_forest.predict(node_embeddings) == -1
        
        # LOF
        lof_anomaly = self.lof.predict(node_embeddings) == -1
        
        # Vote majoritaire (au moins 2 sur 3)
        ensemble_vote = (kpca_anomaly.astype(int) + if_anomaly.astype(int) + lof_anomaly.astype(int)) >= 2
        
        return ensemble_vote
    
    def anomaly_scores(self, node_embeddings):
        """Retourne les scores d'anomalie continus"""
        kpca_projection = self.kpca.transform(node_embeddings)
        reconstruction = self.kpca.inverse_transform(kpca_projection)
        kpca_errors = np.linalg.norm(node_embeddings - reconstruction, axis=1)
        
        if_scores = -self.iso_forest.score_samples(node_embeddings)
        lof_scores = -self.lof.score_samples(node_embeddings)
        
        # Normalisation et combinaison
        kpca_norm = (kpca_errors - np.min(kpca_errors)) / (np.max(kpca_errors) - np.min(kpca_errors) + 1e-10)
        if_norm = (if_scores - np.min(if_scores)) / (np.max(if_scores) - np.min(if_scores) + 1e-10)
        lof_norm = (lof_scores - np.min(lof_scores)) / (np.max(lof_scores) - np.min(lof_scores) + 1e-10)
        
        return (kpca_norm + if_norm + lof_norm) / 3.0


