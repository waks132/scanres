class PPOEvasionAgent:
    """
    Agent PPO pour optimisation des stratégies d'évasion.
    A1 CORRECTIONS:
    - Reward normalisée par log(1 + degree(target))
    - État normalisé par statistiques locales du sous-graphe ego
    """
    
    def __init__(self, state_dim=10, action_dim=3, lr=0.001, gamma=0.99, epsilon=0.1):
        self.state_dim = state_dim
        self.action_dim = action_dim
        self.lr = lr
        self.gamma = gamma
        self.epsilon = epsilon
        
        # Réseaux de neurones simples (policy et value)
        self.policy_weights = np.random.randn(state_dim, action_dim) * 0.01
        self.value_weights = np.random.randn(state_dim, 1) * 0.01
        
        # Mémoire d'expérience
        self.memory = []
        
        # A1: Statistiques de normalisation d'état
        self.state_mean = 0.0
        self.state_std = 1.0
        
    def normalize_state(self, state):
        """A1: Normalise l'état par les statistiques locales du nœud cible"""
        return (state - self.state_mean) / self.state_std
    
    def set_normalization_stats(self, mean, std):
        """A1: Définit les statistiques de normalisation pour le nœud cible"""
        self.state_mean = mean
        self.state_std = np.where(std > 1e-8, std, 1.0)
        
    def select_action(self, state):
        """Sélectionne une action selon la policy actuelle (softmax)"""
        # A1: Normalisation d'état avant décision
        norm_state = self.normalize_state(state)
        logits = norm_state @ self.policy_weights
        logits = logits - np.max(logits)  # Stabilité numérique
        probs = np.exp(logits)
        probs = probs / np.sum(probs)
        
        if np.random.random() < self.epsilon:
            return np.random.randint(self.action_dim)
        else:
            return np.argmax(probs)
    
    def store_transition(self, state, action, reward, next_state, done):
        """Stocke une transition dans la mémoire d'expérience"""
        self.memory.append((state, action, reward, next_state, done))
    
    def compute_advantages(self, rewards, values, gamma=0.99, lam=0.95):
        """Calcule les avantages généralisés (GAE)"""
        advantages = np.zeros_like(rewards)
        last_advantage = 0
        
        for t in reversed(range(len(rewards))):
            if t == len(rewards) - 1:
                next_value = 0
            else:
                next_value = values[t + 1]
            
            delta = rewards[t] + gamma * next_value - values[t]
            advantages[t] = delta + gamma * lam * last_advantage
            last_advantage = advantages[t]
        
        return advantages
    
    def update(self, batch_size=32):
        """Met à jour la policy avec PPO (simplifié)"""
        if len(self.memory) < batch_size:
            return
        
        # Échantillonner un batch
        batch = self.memory[:batch_size]
        states = np.array([m[0] for m in batch])
        actions = np.array([m[1] for m in batch])
        rewards = np.array([m[2] for m in batch])
        
        # Calculer les valeurs
        values = states @ self.value_weights
        values = values.flatten()
        
        # Calculer les avantages
        advantages = self.compute_advantages(rewards, values)
        advantages = (advantages - np.mean(advantages)) / (np.std(advantages) + 1e-10)
        
        # Mise à jour policy (gradient ascent avec clipping PPO)
        for i in range(batch_size):
            state = states[i]
            action = actions[i]
            advantage = advantages[i]
            
            logits = state @ self.policy_weights
            logits = logits - np.max(logits)
            probs = np.exp(logits)
            probs = probs / np.sum(probs)
            
            old_prob = probs[action]
            
            # Gradient policy
            grad = np.zeros_like(self.policy_weights)
            for a in range(self.action_dim):
                if a == action:
                    grad[:, a] = state * (1 - probs[a]) * advantage
                else:
                    grad[:, a] = -state * probs[a] * advantage
            
            # Clipping PPO
            ratio = probs[action] / (old_prob + 1e-10)
            clipped_ratio = np.clip(ratio, 0.8, 1.2)
            
            self.policy_weights += self.lr * grad * (1 if ratio < clipped_ratio else 0)
        
        # Mise à jour value function
        for i in range(batch_size):
            state = states[i]
            target_value = rewards[i]
            value_pred = state @ self.value_weights
            value_error = target_value - value_pred
            self.value_weights += self.lr * value_error * state.reshape(-1, 1)
        
        self.memory = []


