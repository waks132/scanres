class HierarchicalCache:
    """Cache hiérarchique L1 (RAM) / L2 (Disque) / L3 (Précalculs)"""
    
    def __init__(self, ttl=60, l2_path='./cache_l2', max_l1_size=100):
        self.l1 = OrderedDict()
        self.l1_timestamps = {}
        self.l1_access_count = {}
        self.ttl = ttl
        self.max_l1_size = max_l1_size
        self.l2_path = l2_path
        self.l3 = {}
        
        # Correction Hit Rate
        self.hits = 0
        self.misses = 0
        
        os.makedirs(l2_path, exist_ok=True)
        
    def _hash_key(self, matrix_type, k, matrix_data):
        data_hash = hashlib.md5(matrix_data.tobytes()).hexdigest()[:16]
        return f"{matrix_type}_k{k}_{data_hash}"
    
    def get(self, matrix_type, k, matrix_data):
        key = self._hash_key(matrix_type, k, matrix_data)
        
        if key in self.l1:
            if time.time() - self.l1_timestamps.get(key, 0) < self.ttl:
                self.l1.move_to_end(key)
                self.l1_access_count[key] = self.l1_access_count.get(key, 0) + 1
                self.hits += 1
                return self.l1[key]
            else:
                del self.l1[key]
                del self.l1_timestamps[key]
                del self.l1_access_count[key]
        
        l2_file = os.path.join(self.l2_path, f"{key}.npz")
        if os.path.exists(l2_file):
            data = np.load(l2_file, allow_pickle=True)
            result = (data['U'], data['S'], data['Vt'])
            self._put_l1(key, result)
            self.hits += 1
            return result
        
        self.misses += 1
        return None
    
    def put(self, matrix_type, k, matrix_data, result):
        key = self._hash_key(matrix_type, k, matrix_data)
        self._put_l1(key, result)
        self._put_l2(key, result)
    
    def _put_l1(self, key, result):
        self.l1[key] = result
        self.l1_timestamps[key] = time.time()
        self.l1_access_count[key] = 1
        self.l1.move_to_end(key)
        while len(self.l1) > self.max_l1_size:
            oldest = next(iter(self.l1))
            del self.l1[oldest]
            del self.l1_timestamps[oldest]
            del self.l1_access_count[oldest]
    
    def _put_l2(self, key, result):
        l2_file = os.path.join(self.l2_path, f"{key}.npz")
        U, S, Vt = result
        np.savez_compressed(l2_file, U=U, S=S, Vt=Vt)
    
    def preload_l3(self, engine):
        print("Précalcul des centralités (Cache L3)...")
        self.l3['eigenvector'] = nx.eigenvector_centrality(engine.G, weight='weight', max_iter=1000)
        # Optimisation: Betweenness avec échantillonnage k=50 pour accélérer
        self.l3['betweenness'] = nx.betweenness_centrality(engine.G, weight='weight', k=50 if len(engine.G) > 100 else None)
        self.l3['closeness'] = nx.closeness_centrality(engine.G)
        self.l3['pagerank'] = nx.pagerank(engine.G, weight='weight')
        self.l3['degree'] = dict(engine.G.degree(weight='weight'))
        print(f"Cache L3 prêt: {len(self.l3)} métriques.")
    
    def get_l3(self, metric_name):
        return self.l3.get(metric_name, {})
    
    def stats(self):
        """Retourne les statistiques du cache (Correction Hit Rate)"""
        total_access = self.hits + self.misses
        hit_rate = self.hits / total_access if total_access > 0 else 0.0
        return {
            'l1_size': len(self.l1),
            'l2_files': len([f for f in os.listdir(self.l2_path) if f.endswith('.npz')]),
            'l3_metrics': len(self.l3),
            'l1_hit_rate': hit_rate
        }


